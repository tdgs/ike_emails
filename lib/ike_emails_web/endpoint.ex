defmodule IkeEmailsWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :ike_emails

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_ike_emails_key",
    signing_salt: "PWRYyiAy",
    same_site: "Lax"
  ]

  # No Sentry.LiveViewHook: it would send the form values of every event (the invoices)
  # and every message the LiveView gets to Sentry with any error of the process
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :ike_emails,
    gzip: not code_reloading?,
    only: IkeEmailsWeb.static_paths()

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :ike_emails

    # For the dashboard, which is only routed in development
    plug Phoenix.LiveDashboard.RequestLogger,
      param_key: "request_logger",
      cookie_key: "request_logger"
  end

  # Kamal's proxy asks this before it sends traffic to a new container
  plug :health_check

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # A multipart body is the PDF of a statement (PUT /api/statements/:month) and a little
  # more around it. Without the length, Plug refuses anything over 8 MB with a 413
  plug Plug.Parsers,
    parsers: [
      :urlencoded,
      {:multipart, length: IkeEmails.Storage.max_pdf_bytes() + 1_000_000},
      :json
    ],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  # The request goes with the errors reported to Sentry, but not its body: what is
  # pushed to the API (the bank transactions) must stay with us. The cookies and
  # the authorization header are scrubbed by default. There is no
  # Sentry.PlugCapture, it is for Cowboy and reports twice on Bandit, see
  # IkeEmails.Application for how the errors are reported.
  plug Sentry.PlugContext, body_scrubber: nil

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug IkeEmailsWeb.Router

  defp health_check(%Plug.Conn{request_path: "/up"} = conn, _opts) do
    conn |> Plug.Conn.send_resp(200, "ok") |> Plug.Conn.halt()
  end

  defp health_check(conn, _opts), do: conn
end
